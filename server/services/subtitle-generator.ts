/**
 * server/services/subtitle-generator.ts
 *
 * Synchronized Multilingual Subtitle Compiler for SufiPulse Pipeline.
 * 
 * Compiles:
 *  - WebVTT (.vtt)
 *  - SubRip (.srt)
 *  - Advanced SubStation Alpha (.ass) with syllable-level \k karaoke highlighting
 *  - Dual-Subtitle ASS (Original Calligraphy / Script + English translation below)
 */

import fs from 'node:fs';
import path from 'node:path';
import type { MultilingualPackage, MultilingualLineEntry } from './multilingual-pipeline';

export interface SubtitleCompileResult {
  vtt: string;
  srt: string;
  ass: string;
}

export function formatVttTime(seconds: number): string {
  const totalMs = Math.max(0, Math.round(seconds * 1000));
  const hh = Math.floor(totalMs / 3600000);
  const mm = Math.floor((totalMs % 3600000) / 60000);
  const ss = Math.floor((totalMs % 60000) / 1000);
  const ms = totalMs % 1000;
  return `${String(hh).padStart(2, '0')}:${String(mm).padStart(2, '0')}:${String(ss).padStart(2, '0')}.${String(ms).padStart(3, '0')}`;
}

export function formatSrtTime(seconds: number): string {
  return formatVttTime(seconds).replace('.', ',');
}

export function formatAssTime(seconds: number): string {
  const totalMs = Math.max(0, Math.round(seconds * 1000));
  const h = Math.floor(totalMs / 3600000);
  const mm = Math.floor((totalMs % 3600000) / 60000);
  const ss = Math.floor((totalMs % 60000) / 1000);
  const cs = Math.floor((totalMs % 1000) / 10); // centiseconds
  return `${h}:${String(mm).padStart(2, '0')}:${String(ss).padStart(2, '0')}.${String(cs).padStart(2, '0')}`;
}

function getTextForLanguage(line: MultilingualLineEntry, langCode: string): string {
  if (line.isProductionDirection) return '';
  switch (langCode) {
    case 'ur':
      return line.originalText;
    case 'en':
      return line.englishTranslation;
    case 'en-rom':
      return line.romanUrdu;
    case 'ur-deva':
      return line.devanagariUrdu;
    default:
      return line.additionalLanguages?.[langCode] || line.originalText;
  }
}

/**
 * Builds WebVTT string for a specific language
 */
export function compileVtt(pkg: MultilingualPackage, langCode: string): string {
  const lines: string[] = ['WEBVTT', `NOTE Language: ${langCode}`, `NOTE Revision: ${pkg.revision}`, ''];

  let cueIdx = 1;
  for (const entry of pkg.lines) {
    const text = getTextForLanguage(entry, langCode);
    if (!text) continue;

    const start = formatVttTime(entry.startSeconds);
    const end = formatVttTime(entry.endSeconds);

    lines.push(String(cueIdx));
    lines.push(`${start} --> ${end}`);
    lines.push(text);
    lines.push('');
    cueIdx++;
  }

  return lines.join('\n');
}

/**
 * Builds SubRip (SRT) string for a specific language
 */
export function compileSrt(pkg: MultilingualPackage, langCode: string): string {
  const lines: string[] = [];

  let cueIdx = 1;
  for (const entry of pkg.lines) {
    const text = getTextForLanguage(entry, langCode);
    if (!text) continue;

    const start = formatSrtTime(entry.startSeconds);
    const end = formatSrtTime(entry.endSeconds);

    lines.push(String(cueIdx));
    lines.push(`${start} --> ${end}`);
    lines.push(text);
    lines.push('');
    cueIdx++;
  }

  return lines.join('\n');
}

/**
 * Builds Advanced SubStation Alpha (.ass) with Karaoke syllable timing \k<cs>
 * and Dual-Subtitle support (Nastaliq on top, English translation below).
 */
export function compileAss(
  pkg: MultilingualPackage,
  options?: {
    dualSubtitle?: boolean;
    primaryLang?: string;
    secondaryLang?: string;
  }
): string {
  const dual = options?.dualSubtitle !== false;
  const primLang = options?.primaryLang || 'ur';
  const secLang = options?.secondaryLang || 'en';

  const doc: string[] = [
    '[Script Info]',
    '; Script generated by SufiPulse USA Multilingual Engine',
    `Title: SufiPulse Release Master (Rev ${pkg.revision})`,
    'ScriptType: v4.00+',
    'WrapStyle: 0',
    'ScaledBorderAndShadow: yes',
    'YCbCr Matrix: TV.709',
    'PlayResX: 1920',
    'PlayResY: 1080',
    '',
    '[V4+ Styles]',
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
    // Style for Primary Script (e.g. Urdu Nastaliq or Roman Urdu)
    'Style: Mystic_Primary,Arial,48,&H00FFFFFF,&H0000FFFF,&H00101010,&H80000000,-1,0,0,0,100,100,0,0,1,3,0,2,40,40,95,1',
    // Style for Secondary Translation (e.g. English)
    'Style: Mystic_Secondary,Arial,32,&H00A0E0FF,&H00FFFFFF,&H00151515,&H80000000,0,0,0,0,100,100,0,0,1,2,0,2,50,50,45,1',
    '',
    '[Events]',
    'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
  ];

  for (const entry of pkg.lines) {
    if (entry.isProductionDirection) continue;

    const start = formatAssTime(entry.startSeconds);
    const end = formatAssTime(entry.endSeconds);

    let primText = getTextForLanguage(entry, primLang);
    const secText = getTextForLanguage(entry, secLang);

    if (!primText && !secText) continue;

    // If word timings exist on primary language, build syllable-level karaoke \k tags
    if (entry.words && entry.words.length > 0 && primLang === 'ur') {
      let karaokeText = '';
      for (const w of entry.words) {
        const durationCs = Math.max(1, Math.round((w.endSeconds - w.startSeconds) * 100));
        karaokeText += `{\\k${durationCs}}${w.text} `;
      }
      primText = karaokeText.trim();
    }

    if (dual && secText && primText) {
      // Layer 0: Primary script (higher up on screen)
      doc.push(`Dialogue: 0,${start},${end},Mystic_Primary,,0,0,0,,${primText}`);
      // Layer 1: Secondary translation (below primary script)
      doc.push(`Dialogue: 1,${start},${end},Mystic_Secondary,,0,0,0,,${secText}`);
    } else {
      const activeText = primText || secText;
      doc.push(`Dialogue: 0,${start},${end},Mystic_Primary,,0,0,0,,${activeText}`);
    }
  }

  return doc.join('\n');
}

/**
 * Compiles all subtitle formats and saves them to the draft subtitles directory.
 */
export function exportAllSubtitles(
  pkg: MultilingualPackage,
  outputDir: string
): Record<string, SubtitleCompileResult> {
  fs.mkdirSync(outputDir, { recursive: true });

  const results: Record<string, SubtitleCompileResult> = {};
  const langCodes = Object.keys(pkg.languages);

  for (const lang of langCodes) {
    const vtt = compileVtt(pkg, lang);
    const srt = compileSrt(pkg, lang);
    const ass = compileAss(pkg, { dualSubtitle: false, primaryLang: lang });

    fs.writeFileSync(path.join(outputDir, `${lang}.vtt`), vtt, 'utf8');
    fs.writeFileSync(path.join(outputDir, `${lang}.srt`), srt, 'utf8');
    fs.writeFileSync(path.join(outputDir, `${lang}.ass`), ass, 'utf8');

    results[lang] = { vtt, srt, ass };
  }

  // Compile standard Dual-Subtitle Master ASS (Nastaliq + English)
  const masterDualAss = compileAss(pkg, { dualSubtitle: true, primaryLang: 'ur', secondaryLang: 'en' });
  fs.writeFileSync(path.join(outputDir, 'master_dual_urdu_english.ass'), masterDualAss, 'utf8');

  return results;
}
