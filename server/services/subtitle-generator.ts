/**
 * server/services/subtitle-generator.ts
 *
 * Synchronized Multilingual Subtitle Compiler for SufiPulse Pipeline.
 * 
 * Features:
 *  - Nastaliq Arabic script typography (Noto Nastaliq Urdu / Segoe UI) with proper RTL shaping.
 *  - Exact Karaoke \k duration reconciliation (sum of \k durations === line total duration to the centisecond).
 *  - Dual-Subtitle ASS (Calligraphy/Nastaliq on top + English translation below).
 *  - Standard WebVTT (.vtt) and SubRip (.srt).
 */

import fs from 'node:fs';
import path from 'node:path';
import type { MultilingualPackage, MultilingualLineEntry } from './multilingual-pipeline';

export interface SubtitleCompileResult {
  vtt: string;
  srt: string;
  ass: string;
}

export function formatVttTime(seconds: number): string {
  const totalMs = Math.max(0, Math.round(seconds * 1000));
  const hh = Math.floor(totalMs / 3600000);
  const mm = Math.floor((totalMs % 3600000) / 60000);
  const ss = Math.floor((totalMs % 60000) / 1000);
  const ms = totalMs % 1000;
  return `${String(hh).padStart(2, '0')}:${String(mm).padStart(2, '0')}:${String(ss).padStart(2, '0')}.${String(ms).padStart(3, '0')}`;
}

export function formatSrtTime(seconds: number): string {
  return formatVttTime(seconds).replace('.', ',');
}

export function formatAssTime(seconds: number): string {
  const totalMs = Math.max(0, Math.round(seconds * 1000));
  const h = Math.floor(totalMs / 3600000);
  const mm = Math.floor((totalMs % 3600000) / 60000);
  const ss = Math.floor((totalMs % 60000) / 1000);
  const cs = Math.floor((totalMs % 1000) / 10);
  return `${h}:${String(mm).padStart(2, '0')}:${String(ss).padStart(2, '0')}.${String(cs).padStart(2, '0')}`;
}

function getTextForLanguage(line: MultilingualLineEntry, langCode: string): string {
  if (line.isProductionDirection) return '';
  switch (langCode) {
    case 'ur':
      return line.urduNastaliq || line.originalText;
    case 'en':
      return line.englishTranslation;
    case 'en-rom':
      return line.romanUrdu;
    case 'ur-deva':
      return line.devanagariUrdu || line.originalText;
    default:
      return line.additionalLanguages?.[langCode] || line.originalText;
  }
}

export function compileVtt(pkg: MultilingualPackage, langCode: string): string {
  const lines: string[] = ['WEBVTT', `NOTE Language: ${langCode}`, `NOTE Revision: ${pkg.revision}`, ''];

  let cueIdx = 1;
  for (const entry of pkg.lines) {
    const text = getTextForLanguage(entry, langCode);
    if (!text) continue;

    const start = formatVttTime(entry.startSeconds);
    const end = formatVttTime(entry.endSeconds);

    lines.push(String(cueIdx));
    lines.push(`${start} --> ${end}`);
    lines.push(text);
    lines.push('');
    cueIdx++;
  }

  return lines.join('\n');
}

export function compileSrt(pkg: MultilingualPackage, langCode: string): string {
  const lines: string[] = [];

  let cueIdx = 1;
  for (const entry of pkg.lines) {
    const text = getTextForLanguage(entry, langCode);
    if (!text) continue;

    const start = formatSrtTime(entry.startSeconds);
    const end = formatSrtTime(entry.endSeconds);

    lines.push(String(cueIdx));
    lines.push(`${start} --> ${end}`);
    lines.push(text);
    lines.push('');
    cueIdx++;
  }

  return lines.join('\n');
}

/**
 * Builds Advanced SubStation Alpha (.ass) with:
 *  - Proper Nastaliq typography (Noto Nastaliq Urdu, Segoe UI).
 *  - Exact karaoke duration reconciliation (sum of \k durations matches line interval).
 *  - Dual-Subtitle master option (Layer 0 Nastaliq, Layer 1 English).
 */
export function compileAss(
  pkg: MultilingualPackage,
  options?: {
    dualSubtitle?: boolean;
    primaryLang?: string;
    secondaryLang?: string;
    enableKaraoke?: boolean;
    orientation?: 'landscape' | 'portrait';
  }
): string {
  const dual = options?.dualSubtitle !== false;
  const primLang = options?.primaryLang || 'ur';
  const secLang = options?.secondaryLang || 'en';
  const enableKaraoke = options?.enableKaraoke !== false;
  const orientation = options?.orientation || 'landscape';
  const isPortrait = orientation === 'portrait';

  const playResX = isPortrait ? 1080 : 1920;
  const playResY = isPortrait ? 1920 : 1080;

  // Maximum subtitle-group width: 85% relative to the inner cinematic video canvas
  // Margins left/right: (100% - 85%) / 2 = 7.5%
  const marginH = Math.round(playResX * 0.075); // 144px (16:9), 81px (9:16)

  // Typography tailored to resolution and cinematic hierarchy
  // Urdu Nastaliq: Radiant White (&H00FFFFFF), Outline: 3.5, Shadow: 2.0
  // English Translation: Radiant Amber Gold (&H003AD2F7), Outline: 2.5, Shadow: 2.0
  const primaryFontSize = isPortrait ? 46 : 52;
  const secondaryFontSize = isPortrait ? 28 : 34;

  const doc: string[] = [
    '[Script Info]',
    '; Script generated by SufiPulse USA Multilingual Engine',
    `Title: SufiPulse Release Master (Rev ${pkg.revision}) [${orientation.toUpperCase()}]`,
    'ScriptType: v4.00+',
    'WrapStyle: 0',
    'ScaledBorderAndShadow: yes',
    'YCbCr Matrix: TV.709',
    `PlayResX: ${playResX}`,
    `PlayResY: ${playResY}`,
    '',
    '[V4+ Styles]',
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
    // Style for Nastaliq Script / Urdu Calligraphy: White, soft dark outline, Alignment: 5 (Mid-Center)
    `Style: Mystic_Primary,Noto Nastaliq Urdu,${primaryFontSize},&H00FFFFFF,&H0000FFFF,&H0008080A,&HA0000000,-1,0,0,0,100,100,0,0,1,3.5,2.0,5,${marginH},${marginH},0,1`,
    // Style for English Translation: Amber Gold (&H003AD2F7), soft dark outline, Alignment: 5 (Mid-Center)
    `Style: Mystic_Secondary,Georgia,${secondaryFontSize},&H003AD2F7,&H00FFFFFF,&H0008080A,&HA0000000,0,0,0,0,100,100,0,0,1,2.5,2.0,5,${marginH},${marginH},0,1`,
    '',
    '[Events]',
    'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
  ];

  const xCenter = Math.round(playResX * 0.50);
  const yMid = Math.round(playResY * 0.50);

  for (const entry of pkg.lines) {
    if (entry.isProductionDirection) continue;

    const start = formatAssTime(entry.startSeconds);
    const end = formatAssTime(entry.endSeconds);

    let primText = getTextForLanguage(entry, primLang);
    const secText = getTextForLanguage(entry, secLang);

    if (!primText && !secText) continue;

    // Reconcile Karaoke durations so sum(cs) exactly equals (end - start) in centiseconds
    const lineTotalDurationCs = Math.max(1, Math.round((entry.endSeconds - entry.startSeconds) * 100));

    if (enableKaraoke && entry.words && entry.words.length > 0 && primLang === 'ur') {
      const words = entry.words;
      const rawDurations = words.map((w) => Math.max(1, Math.round((w.endSeconds - w.startSeconds) * 100)));
      const rawSum = rawDurations.reduce((acc, v) => acc + v, 0);

      // Distribute any remainder or stretch proportionally to guarantee exact duration match
      let reconciledDurations: number[];
      if (rawSum > 0) {
        const factor = lineTotalDurationCs / rawSum;
        reconciledDurations = rawDurations.map((d) => Math.max(1, Math.round(d * factor)));
        const newSum = reconciledDurations.reduce((acc, v) => acc + v, 0);
        const diff = lineTotalDurationCs - newSum;
        // Adjust last word by the rounding delta
        reconciledDurations[reconciledDurations.length - 1] = Math.max(
          1,
          reconciledDurations[reconciledDurations.length - 1] + diff
        );
      } else {
        const perWord = Math.floor(lineTotalDurationCs / words.length);
        reconciledDurations = words.map((_, i) =>
          i === words.length - 1 ? lineTotalDurationCs - perWord * (words.length - 1) : perWord
        );
      }

      let karaokeText = '';
      for (let wIdx = 0; wIdx < words.length; wIdx++) {
        karaokeText += `{\\k${reconciledDurations[wIdx]}}${words[wIdx].text} `;
      }
      primText = karaokeText.trim();
    }

    // Dynamic vertical calculation ensuring combined group is centered at exact 50%
    // Urdu center is approx 46%, English center is approx 54%
    if (dual && secText && primText) {
      const cleanPrim = primText.replace(/\{\\k\d+\}/g, '');
      const urduLineBreakCount = (cleanPrim.match(/\\N|\n/g)?.length || 0);
      const engLineBreakCount = (secText.match(/\\N|\n/g)?.length || 0);

      const urduCharWrapThreshold = isPortrait ? 26 : 48;
      const engCharWrapThreshold = isPortrait ? 30 : 54;

      const urduLines = Math.max(1, urduLineBreakCount + 1 + (cleanPrim.length > urduCharWrapThreshold ? 1 : 0));
      const engLines = Math.max(1, engLineBreakCount + 1 + (secText.length > engCharWrapThreshold ? 1 : 0));

      const urduLineHeight = isPortrait ? 56 : 64;
      const engLineHeight = isPortrait ? 36 : 42;
      const interLangGap = isPortrait ? (urduLines > 1 || engLines > 1 ? 20 : 36) : (urduLines > 1 || engLines > 1 ? 16 : 24);

      const hUrdu = urduLines * urduLineHeight;
      const hEng = engLines * engLineHeight;
      const hTotal = hUrdu + interLangGap + hEng;

      // Group vertical center = exact 50% of canvas
      const yTop = yMid - Math.round(hTotal / 2);

      // Urdu center is anchored at ~46% of PlayResY
      const yUrdu = Math.round(yTop + hUrdu / 2);
      // English center is anchored at ~54% of PlayResY
      const yEnglish = Math.round(yTop + hUrdu + interLangGap + hEng / 2);

      doc.push(`Dialogue: 0,${start},${end},Mystic_Primary,,0,0,0,,{\\an5\\pos(${xCenter},${yUrdu})}${primText}`);
      doc.push(`Dialogue: 1,${start},${end},Mystic_Secondary,,0,0,0,,{\\an5\\pos(${xCenter},${yEnglish})}${secText}`);
    } else {
      const activeText = primText || secText;
      const styleName = primText ? 'Mystic_Primary' : 'Mystic_Secondary';
      doc.push(`Dialogue: 0,${start},${end},${styleName},,0,0,0,,{\\an5\\pos(${xCenter},${yMid})}${activeText}`);
    }
  }

  return doc.join('\n');
}


export function compileQuadMusicAss(
  pkg: MultilingualPackage,
  orientation: 'landscape' | 'portrait' = 'landscape'
): string {
  const isPortrait = orientation === 'portrait';
  const playResX = isPortrait ? 1080 : 1920;
  const playResY = isPortrait ? 1920 : 1080;
  const marginH = Math.round(playResX * 0.08);

  // Four-line readability-first hierarchy: Roman Urdu / Urdu / Hindi / English.
  // English and Urdu are optically compensated so all four rows read at comparable visual weight.
  const romanSize = isPortrait ? 50 : 40;
  // Nastaliq has a small x-height: it needs a much larger point size than Latin/Devanagari
  // to read at the same visual weight in the burned video.
  const urduSize = isPortrait ? 74 : 60;
  const hindiSize = isPortrait ? 50 : 40;
  const englishSize = isPortrait ? 50 : 40;
  const outline = isPortrait ? 2.4 : 2.8;
  const shadow = isPortrait ? 0.8 : 1.0;

  // Per-row heights (the Urdu row is taller) stacked and centred as one block.
  const rowH = {
    roman: isPortrait ? 62 : 48,
    urdu: isPortrait ? 112 : 88,
    hindi: isPortrait ? 62 : 48,
    english: isPortrait ? 62 : 48,
  };
  const rowSpace = isPortrait ? 6 : 4;
  const blockH = rowH.roman + rowH.urdu + rowH.hindi + rowH.english + rowSpace * 3;
  const yCenter = Math.round(playResY * 0.52);
  const yBlockTop = yCenter - Math.round(blockH / 2);
  const yRoman = Math.round(yBlockTop + rowH.roman / 2);
  const yUrdu = Math.round(yBlockTop + rowH.roman + rowSpace + rowH.urdu / 2);
  const yHindi = Math.round(yBlockTop + rowH.roman + rowSpace + rowH.urdu + rowSpace + rowH.hindi / 2);
  const yEnglish = Math.round(yBlockTop + rowH.roman + rowSpace + rowH.urdu + rowSpace + rowH.hindi + rowSpace + rowH.english / 2);

  const doc: string[] = [
    '[Script Info]',
    '; SufiPulse USA - Four-Line Music Caption Master',
    `Title: SufiPulse Quad Caption Master (Rev ${pkg.revision}) [${orientation.toUpperCase()}]`,
    'ScriptType: v4.00+',
    'WrapStyle: 2',
    'ScaledBorderAndShadow: yes',
    'YCbCr Matrix: TV.709',
    `PlayResX: ${playResX}`,
    `PlayResY: ${playResY}`,
    '',
    '[V4+ Styles]',
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
    `Style: RomanUrdu,Segoe UI Semibold,${romanSize},&H00FFFFFF,&H00FFFFFF,&H00101010,&H64000000,-1,0,0,0,100,100,0,0,1,${outline},${shadow},5,${marginH},${marginH},0,1`,
    `Style: English,Segoe UI,${englishSize},&H00EAEAEA,&H00EAEAEA,&H00101010,&H64000000,0,0,0,0,100,100,0,0,1,${outline},${shadow},5,${marginH},${marginH},0,1`,
    `Style: Urdu,Noto Nastaliq Urdu,${urduSize},&H00FFFFFF,&H00FFFFFF,&H00101010,&H64000000,-1,0,0,0,100,100,0,0,1,${outline},${shadow},5,${marginH},${marginH},0,1`,
    `Style: Hindi,Nirmala UI,${hindiSize},&H00FFFFFF,&H00FFFFFF,&H00101010,&H64000000,-1,0,0,0,100,100,0,0,1,${outline},${shadow},5,${marginH},${marginH},0,1`,
    '',
    '[Events]',
    'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
  ];

  const xCenter = Math.round(playResX * 0.50);

  const balanceQuotes = (value: string) => {
    let text = value
      .replace(/[“”]/g, '"')
      .replace(/[‘’]/g, "'")
      .trim();

    const doubleCount = (text.match(/"/g) || []).length;
    if (doubleCount % 2 !== 0) {
      text = text.startsWith('"') ? `${text}"` : `"${text}`;
    }

    const singleCount = (text.match(/'/g) || []).length;
    if (singleCount % 2 !== 0) {
      text = text.startsWith("'") ? `${text}'` : `'${text}`;
    }

    return text;
  };

  const sanitize = (value: string) =>
    balanceQuotes(
      value
        .replace(/\\N|\r?\n/g, ' ')
        .replace(/\s+/g, ' ')
        .trim()
    );

  // Readability-first line scaling. Short lines stay large. Long lines shrink before wrapping.
  const fitSize = (text: string, base: number, min: number, softLimit: number) => {
    const length = Array.from(text).length;
    if (length <= softLimit) return base;
    const ratio = softLimit / Math.max(softLimit, length);
    return Math.max(min, Math.round(base * Math.max(0.72, ratio)));
  };

  for (const entry of pkg.lines) {
    if (entry.isProductionDirection) continue;
    const roman = sanitize(entry.romanUrdu || entry.originalText || '');
    const english = sanitize(entry.englishTranslation || '');
    const urdu = sanitize(entry.urduNastaliq || '');
    const hindi = sanitize(entry.devanagariUrdu || entry.originalText || '');
    if (!roman && !english && !urdu && !hindi) continue;

    const start = formatAssTime(entry.startSeconds);
    const end = formatAssTime(entry.endSeconds);

    const romanFs = fitSize(roman, romanSize, isPortrait ? 40 : 32, isPortrait ? 30 : 52);
    const urduFs = fitSize(urdu, urduSize, isPortrait ? 54 : 46, isPortrait ? 26 : 34);
    const hindiFs = fitSize(hindi, hindiSize, isPortrait ? 40 : 32, isPortrait ? 28 : 48);
    const englishFs = fitSize(english, englishSize, isPortrait ? 40 : 32, isPortrait ? 34 : 60);

    // Exact visual order: Roman Urdu → Urdu → Hindi → English.
    if (roman) doc.push(`Dialogue: 0,${start},${end},RomanUrdu,,0,0,0,,{\\an5\\pos(${xCenter},${yRoman})\\fs${romanFs}}${roman}`);
    if (urdu) doc.push(`Dialogue: 1,${start},${end},Urdu,,0,0,0,,{\\an5\\pos(${xCenter},${yUrdu})\\fs${urduFs}}${urdu}`);
    if (hindi) doc.push(`Dialogue: 2,${start},${end},Hindi,,0,0,0,,{\\an5\\pos(${xCenter},${yHindi})\\fs${hindiFs}}${hindi}`);
    if (english) doc.push(`Dialogue: 3,${start},${end},English,,0,0,0,,{\\an5\\pos(${xCenter},${yEnglish})\\fs${englishFs}}${english}`);
  }

  return doc.join('\n');
}

export function exportAllSubtitles(
  pkg: MultilingualPackage,
  outputDir: string
): Record<string, SubtitleCompileResult> {
  fs.mkdirSync(outputDir, { recursive: true });

  const results: Record<string, SubtitleCompileResult> = {};
  const langCodes = Object.keys(pkg.languages);

  for (const lang of langCodes) {
    const vtt = compileVtt(pkg, lang);
    const srt = compileSrt(pkg, lang);
    const ass = compileAss(pkg, { dualSubtitle: false, primaryLang: lang, enableKaraoke: true });

    fs.writeFileSync(path.join(outputDir, `${lang}.vtt`), vtt, 'utf8');
    fs.writeFileSync(path.join(outputDir, `${lang}.srt`), srt, 'utf8');
    fs.writeFileSync(path.join(outputDir, `${lang}.ass`), ass, 'utf8');

    results[lang] = { vtt, srt, ass };
  }

  // Four-Line Music Master: Roman Urdu / English / Urdu / Hindi - 16:9
  const masterQuadAss = compileQuadMusicAss(pkg, 'landscape');
  fs.writeFileSync(path.join(outputDir, 'master_quad_roman_english_urdu_hindi.ass'), masterQuadAss, 'utf8');

  // Four-Line Music Master: Roman Urdu / English / Urdu / Hindi - 9:16
  const masterQuadPortraitAss = compileQuadMusicAss(pkg, 'portrait');
  fs.writeFileSync(path.join(outputDir, 'master_quad_roman_english_urdu_hindi_portrait.ass'), masterQuadPortraitAss, 'utf8');

  // Keep older filenames synchronized so existing routes and drafts remain valid.
  fs.writeFileSync(path.join(outputDir, 'master_triple_roman_english_hindi.ass'), masterQuadAss, 'utf8');
  fs.writeFileSync(path.join(outputDir, 'master_triple_roman_english_hindi_portrait.ass'), masterQuadPortraitAss, 'utf8');
  fs.writeFileSync(path.join(outputDir, 'master_dual_urdu_english.ass'), masterQuadAss, 'utf8');
  fs.writeFileSync(path.join(outputDir, 'master_dual_urdu_english_portrait.ass'), masterQuadPortraitAss, 'utf8');

  return results;
}
